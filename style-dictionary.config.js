// Format: emit the brand-color overrides for ledoweb_branding.

StyleDictionary.registerFormat({
    name: "scss/brand-variables",
    format: ({dictionary}) => {
        const get = (path) =>
            dictionary.allTokens.find((t) => t.path.join(".") === path);
        const primary = get("global.color.brand.primary");
        const secondary = get("global.color.brand.secondary");
        const navDark = get("global.color.portal.nav-dark");
        const sidebarLight = get("global.color.portal.sidebar-light");
        const border = get("global.color.portal.border");

        return [
            HEADER.replace("`pnpm run tokens`", "`pnpm run tokens` (in odoo-design-system)"),
            "// Drop this file into your branding module's `static/src/scss/` and list",
            "// it in `web._assets_primary_variables` so Bootstrap compiles $primary",
            "// correctly against it.",
            "",
            "// Color resolution chain in Odoo 18/19:",
            "//   $o-enterprise-color → base-1 palette 'o-color-1' → $-main-color",
            "//   → 'primary' → $primary. Overriding $o-enterprise-color here",
            "//   (before primary_variables.scss !default) cascades through the",
            "//   entire system.",
            "",
            primary &&
                `$o-enterprise-color: ${primary.$value};\n$o-community-color: ${primary.$value};\n$o-brand-odoo: ${primary.$value};\n$o-brand-primary: ${primary.$value};`,
            secondary && `\n// Lighter variant for hover states\n$o-brand-lighten: ${secondary.$value};`,
            "",
            "// Portal chrome",
            navDark && `$o-portal-nav-dark: ${navDark.$value};`,
            sidebarLight && `$o-portal-sidebar-light: ${sidebarLight.$value};`,
            border && `$o-portal-border: ${border.$value};`,
            "",
        ]
            .filter(Boolean)
            .join("\n");
    },
});

